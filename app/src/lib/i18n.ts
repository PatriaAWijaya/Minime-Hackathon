export type Lang = 'id' | 'en' | 'zh';

export const LANG_LS = 'minime.lang';
export const DEFAULT_LANG: Lang = 'id';
export const LANGS: Lang[] = ['id', 'en', 'zh'];
export const LANG_NAMES: Record<Lang, string> = {
  id: 'Bahasa Indonesia',
  en: 'English',
  zh: '中文',
};

let current: Lang = DEFAULT_LANG;
try {
  const saved = window.localStorage.getItem(LANG_LS);
  if (saved === 'id' || saved === 'en' || saved === 'zh') current = saved;
} catch {
  current = DEFAULT_LANG;
}

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
  try {
    window.localStorage.setItem(LANG_LS, lang);
  } catch {
    // storage unavailable: language stays for this session only
  }
}

