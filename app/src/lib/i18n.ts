function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  let out = template;
  for (const [k, v] of Object.entries(vars)) {
    out = out.split('{' + k + '}').join(String(v));
  }
  return out;
}

/**
 * Translate a key. `lang` defaults to the module's current language;
 * App.svelte passes its reactive `lang` state so markup re-renders on
 * switch. Unknown keys fall back to the ID value, never to an empty
 * string; a missing key in EN/ZH falls back to ID (never blank UI).
 */
export function t(key: string, lang?: Lang, vars?: Record<string, string | number>): string {
  const l = lang ?? current;
  const dict = DICTS[l] ?? ID;
  const value = dict[key] ?? ID[key] ?? key;
  return fill(value, vars);
}

/** Module-language translate (for v5logic/gates/chat/postiz/backend-data). */
export function tr(key: string, vars?: Record<string, string | number>): string {
  return t(key, current, vars);
}
